const toolNames = [
  'list_instances',
  'list_tasks',
  'describe_task',
  'start_tasks',
  'stop_tasks',
  'get_run_status',
  'capture_screen',
];
const errorCodes = [
  'instance_not_found',
  'task_not_found',
  'option_not_found',
  'invalid_option',
  'sensitive_option',
  'configuration_required',
  'stale_context',
  'instance_busy',
  'request_conflict',
  'run_not_found',
  'not_connected',
  'permission_denied',
  'resource_exhausted',
  'execution_failed',
];
const paramNames = [
  'instance_id',
  'task_name',
  'option_key',
  'cursor',
  'limit',
  'context_revision',
  'request_id',
  'tasks',
  'run_id',
  'after',
];

interface Translation {
  ui: string[];
  instructions: string;
  tools: [string, string][];
  params: string[];
  errors: string[];
}

function makeLocale(value: Translation) {
  const [
    enabled,
    enabledHint,
    requiresWebServer,
    address,
    copy,
    copied,
    executionEnabled,
    executionHint,
    screenshotEnabled,
    screenshotHint,
    logStart,
    logStop,
  ] = value.ui;
  const errors = Object.fromEntries(errorCodes.map((key, index) => [key, value.errors[index]]));
  return {
    enabled,
    enabledHint,
    requiresWebServer,
    address,
    copy,
    copied,
    pi: {
      executionEnabled,
      executionHint,
      screenshotEnabled,
      screenshotHint,
      logStart,
      logStop,
      errors,
      server: {
        instructions: value.instructions,
        errors,
        tools: Object.fromEntries(
          toolNames.map((name, index) => [
            name,
            {
              title: value.tools[index][0],
              description: value.tools[index][1],
            },
          ]),
        ),
        params: Object.fromEntries(paramNames.map((name, index) => [name, value.params[index]])),
      },
    },
  };
}

