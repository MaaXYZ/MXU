import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Marked, Renderer } from 'marked';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((argument) => argument !== '--check')) {
  throw new Error('Usage: node scripts/generate.mjs [--check]');
}
const read = (relative) => fs.readFile(path.join(root, relative), 'utf8');
const escapeHtml = (value) =>
  value.replace(
    /[&<>"']/g,
    (character) =>
      ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;',
      })[character],
  );

// Array order is the demo order. Keep existing numbers stable when adding ideas.
const ideas = JSON.parse(await read('ideas.json'));
if (!Array.isArray(ideas) || ideas.some((idea, index) => idea.number !== index + 1)) {
  throw new Error('ideas.json must be an ordered array with stable, consecutive numbers.');
}
const categories = ['角色', '空间', '状态', '交互', '叙事'];
if (ideas.some((idea) => !categories.includes(idea.category))) {
  throw new Error('ideas.json contains an unknown category.');
}
const ideasJavaScript =
  '// Generated from ../ideas.json. Run npm run generate; do not edit this file.\n' +
  `window.MXU_IDEAS = ${JSON.stringify(ideas, null, 2)};\n`;
const ideasMarkdown = [
  '<!-- Generated from ideas.json. Run npm run generate; do not edit this file. -->',
  '',
  '# MXU 皮肤创意清单',
  '',
  '本页收集可供讨论的视觉与交互方向。L1 / L2 表示建议实现层级；部分创意还需要额外公开宿主槽位、只读状态或语义动作，不代表 [v0.1 草案](protocol.md) 已经支持。所有趣味表现均应有静态模式，并保留直接、可理解的任务操作。',
  '',
  '六个已做成概念 demo 的方向见 [设计入口](README.md)。下列 24 条用于继续扩展，不是已经完成的功能。编号与 [交互 demo](demo/index.html#ideas) 一致，按类别阅读时保留原编号。唯一内容源为 [ideas.json](ideas.json)。',
  '',
  ...categories.flatMap((category) => [
    `## ${category}`,
    '',
    ...ideas
      .filter((idea) => idea.category === category)
      .flatMap((idea) => [
        `### IDEA ${String(idea.number).padStart(2, '0')} · ${idea.title}`,
        '',
        idea.concept,
        '',
        `- 建议层级：**${idea.level}**。`,
        `- 所需能力：${idea.capability.join('、')}。`,
        `- 操作兜底：${idea.restraint}`,
        '',
      ]),
  ]),
].join('\n');

// Markdown links are relative to skin-system/, whereas generated HTML is in demo/.
// Preserve external URLs, absolute URLs and same-document fragments verbatim.
function fromDemo(href) {
  return /^(?:[a-z][a-z\d+.-]*:|\/|#)/i.test(href) ? href : `../${href}`;
}
const headings = [];
const seenIds = new Map();
const renderer = new Renderer();
renderer.heading = function (token) {
  const label = token.text.replace(/[`*_]/g, '');
  const base =
    label
      .normalize('NFKC')
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s-]/gu, '')
      .trim()
      .replace(/\s+/g, '-') || 'section';
  const count = (seenIds.get(base) || 0) + 1;
  seenIds.set(base, count);
  const id = count === 1 ? base : `${base}-${count}`;
  headings.push({ depth: token.depth, id, label });
  return `<h${token.depth} id="${escapeHtml(id)}">${this.parser.parseInline(token.tokens)}</h${token.depth}>\n`;
};
renderer.link = function (token) {
  return Renderer.prototype.link.call(this, { ...token, href: fromDemo(token.href) });
};
renderer.image = function (token) {
  return Renderer.prototype.image.call(this, { ...token, href: fromDemo(token.href) });
};
renderer.table = function (token) {
  return `<div class="table-wrap">\n${Renderer.prototype.table.call(this, token)}</div>\n`;
};
const markdown = await read('protocol.md');
const content = new Marked({ renderer, gfm: true }).parse(markdown);
const title = headings.find((heading) => heading.depth === 1)?.label;
if (!title) throw new Error('protocol.md must contain a level-one title.');
const toc = headings
  .filter((heading) => [2, 3].includes(heading.depth))
  .map(
    (heading) =>
      `          <a href="#${escapeHtml(heading.id)}" data-depth="${heading.depth}">${escapeHtml(heading.label)}</a>`,
  )
  .join('\n');
const replacements = {
  title: escapeHtml(title),
  styles: (await read('scripts/protocol.css')).trimEnd(),
  toc,
  content: content.trimEnd(),
};
const protocolHtml = (await read('scripts/protocol.template.html')).replace(
  /\{\{(title|styles|toc|content)\}\}/g,
  (_, name) => replacements[name],
);
const outputs = new Map([
  ['demo/ideas.js', ideasJavaScript],
  ['ideas.md', ideasMarkdown],
  ['demo/protocol.html', protocolHtml],
]);
const stale = [];
for (const [relative, value] of outputs) {
  const expected = value.trimEnd() + '\n';
  if (check) {
    const actual = await read(relative).catch((error) => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (actual !== expected) stale.push(relative);
  } else {
    await fs.writeFile(path.join(root, relative), expected);
    console.log(`Generated ${relative}`);
  }
}
if (stale.length) {
  console.error(`Generated files are stale: ${stale.join(', ')}. Run npm run generate.`);
  process.exitCode = 1;
} else if (check) {
  console.log(`Generated files are current (${outputs.size} files).`);
}
